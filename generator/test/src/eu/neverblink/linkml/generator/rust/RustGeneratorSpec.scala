    "make an enum of a class and its subclasses" in {
      val schema =
        """classes:
          |  Animal:
          |    attributes:
          |      name:
          |  Dog:
          |    is_a: Animal
          |    attributes:
          |      breed:
          |  Cat:
          |    is_a: Animal
          |  Shelter:
          |    attributes:
          |      animals:
          |        range: Animal
          |        multivalued: true
          |        inlined_as_list: true
          |""".stripMargin
      val code = lib(schema)
      // Animal isn't abstract, so it is a variant too. It comes last, as it would also read the data
      // of a Cat or a Dog.
      code should include(
        """#[derive(Debug, Clone, PartialEq)]
          |#[cfg_attr(feature = "serde", derive(Serialize, Deserialize))]
          |#[cfg_attr(feature = "serde", serde(untagged))]
          |pub enum AnimalOrSubtype {
          |    Cat(Cat),
          |    Dog(Dog),
          |    Animal(Animal),
          |}
          |""".stripMargin,
      )
      code should include("impl From<Dog> for AnimalOrSubtype {")
      code should include("pub animals: Option<Vec<AnimalOrSubtype>>")
      // A struct has the slots of its ancestors
      code should include("pub struct Dog {\n    #[cfg_attr(feature = \"serde\", serde(default))]")
      val abstractBase = lib(schema.replace("  Animal:\n", "  Animal:\n    abstract: true\n"))
      abstractBase should include("pub enum AnimalOrSubtype {\n    Cat(Cat),\n    Dog(Dog),\n}")
    }

    "pick the variant of a class by its type designator" in {
