        "'MyEnum'. Rename one of them to generate Rust."
      the[IllegalArgumentException] thrownBy lib("classes:\n  HashMap:\n") should have message
        "class 'HashMap' and the generated code both map to the Rust name 'HashMap'. " +
        "Rename one of them to generate Rust."
    }

    "write a slot with an alias under the alias, and read either name" in {
      val code = lib(
        """classes:
          |  A:
          |    attributes:
          |      long_name:
          |        alias: name
          |""".stripMargin,
      )
      code should include(
        """    #[cfg_attr(feature = "serde", serde(rename = "name"))]
