          |""".stripMargin,
      )
    }

    "make an enum of each enum" in {
      val code = lib(
        """enums:
          |  Shift:
          |    permissible_values:
          |      day:
          |      night shift:
          |      Day:
          |      "-":
          |""".stripMargin,
      )
      // The serde names are written even if serde isn't a default feature. A duplicate name gets
      // a `_`, and a name without letters or digits is `V`.
      item(code, "pub enum Shift {") shouldBe
        """pub enum Shift {
          |    #[cfg_attr(feature = "serde", serde(rename = "day"))]
          |    Day,
          |    #[cfg_attr(feature = "serde", serde(rename = "night shift"))]
          |    NightShift,
          |    #[cfg_attr(feature = "serde", serde(rename = "Day"))]
          |    Day_,
          |    #[cfg_attr(feature = "serde", serde(rename = "-"))]
          |    V,
          |}""".stripMargin
      code should include(
        """                "night shift" | "NightShift" => Ok(Shift::NightShift),""",
      )
      code should include("""            Shift::NightShift => f.write_str("night shift"),""")
      code should include("typing.Literal['day', 'night shift', 'Day', '-']")
    }

    "make an enum without permissible values a String" in {
      val code = lib(
