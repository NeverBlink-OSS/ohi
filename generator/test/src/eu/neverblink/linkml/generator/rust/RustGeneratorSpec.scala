package eu.neverblink.linkml.generator.rust

import eu.neverblink.linkml.generator.options.RustGeneratorOptions
import eu.neverblink.linkml.schemaview.{SchemaIssues, SchemaView}
import eu.neverblink.linkml.tests.ModelCatalogue
import org.scalatest.matchers.should.Matchers
import org.scalatest.wordspec.AnyWordSpec

class RustGeneratorSpec extends AnyWordSpec, Matchers {
  def load(body: String, name: String = "zoo"): SchemaView =
    SchemaIssues.orThrow(
      SchemaView.loadSchemaViewFromString(
        s"""id: https://example.org/rust/test/
           |name: $name
           |prefixes:
           |  linkml: https://w3id.org/linkml/
           |  ex: https://example.org/rust/test/
           |default_prefix: ex
           |imports:
           |  - linkml:types
           |$body""".stripMargin,
      ),
    )

  def files(
      body: String,
      options: RustGeneratorOptions = RustGeneratorOptions(),
  ): Map[String, String] =
    RustGenerator(using load(body)).generateFiles(options).toMap

  def lib(body: String, options: RustGeneratorOptions = RustGeneratorOptions()): String =
    files(body, options)("src/lib.rs")

  def poly(body: String): String = files(body)("src/poly.rs")

  /** The text of an item, from its first line to the next empty line. */
  def item(code: String, start: String): String = {
    val from = code.indexOf(start)
    withClue(s"no '$start' in:\n$code\n")(from should be >= 0)
    val to = code.indexOf("\n\n", from)
    code.substring(from, if to < 0 then code.length else to)
  }

  private val person =
    """classes:
      |  Person:
      |    attributes:
      |      id:
      |        identifier: true
      |      name:
      |        required: true
      |      nicknames:
      |        multivalued: true
      |      age:
      |        range: integer
      |      born:
      |        range: date
      |""".stripMargin

  "RustGenerator" should {
    "write a crate" in {
      val crate = files(person)
      crate.keySet shouldBe Set(
        "Cargo.toml",
        "pyproject.toml",
        "src/lib.rs",
        "src/serde_utils.rs",
        "src/poly.rs",
        "src/poly_containers.rs",
        "src/stub_utils.rs",
        "src/bin/stub_gen.rs",
      )
      crate("Cargo.toml") should startWith(
        "# Generated by ohi LinkML from https://example.org/rust/test/\n# DO NOT EDIT.\n",
      )
      crate.removed("Cargo.toml").removed("pyproject.toml").values.foreach(
        _ should startWith("// Generated by ohi LinkML from https://example.org/rust/test/\n"),
      )
      crate("Cargo.toml") should include(
        """[package]
          |name = "zoo"
          |version = "0.0.0"
          |edition = "2021"
          |
          |[lib]
          |name = "zoo"
          |crate-type = ["lib"]
          |""".stripMargin,
      )
      crate("Cargo.toml") should include(
        """[features]
          |default = []
          |pyo3 = ["dep:pyo3"]
          |serde = ["dep:serde", "dep:yaml_serde", "dep:serde_path_to_error"]
          |stubgen = ["dep:pyo3-stub-gen", "pyo3"]
          |""".stripMargin,
      )
      crate("Cargo.toml") should include(
        "chrono = { version = \"0.4.41\", features = [\"serde\"] }",
      )
      crate("src/bin/stub_gen.rs") should include("let stub = zoo::stub_info()?;")
      crate("pyproject.toml") should include("name = \"zoo\"")
    }

    "turn the features on by default and make a Python module with the options" in {
      val crate = files(person, RustGeneratorOptions(serde = true, pyo3 = true))
      crate("Cargo.toml") should include("crate-type = [\"cdylib\", \"rlib\"]")
      crate("Cargo.toml") should include("default = [\"pyo3\", \"serde\"]")
      crate("src/lib.rs") should include(
        """#[cfg(feature = "pyo3")]
          |#[pymodule]
          |#[pyo3(name = "zoo")]
          |fn zoo(m: &Bound<'_, PyModule>) -> PyResult<()> {
          |    m.add_class::<Person>()?;
          |    Ok(())
          |}
          |""".stripMargin,
      )
    }

    "use a semantic version of the schema as the crate version" in {
      val crate = RustGenerator(using load("version: 1.2.3\n" + person)).generateFiles().toMap
      crate("Cargo.toml") should include("version = \"1.2.3\"")
      // Cargo rejects other versions
      val other = RustGenerator(using load("version: '2024-01'\n" + person)).generateFiles().toMap
      other("Cargo.toml") should include("version = \"0.0.0\"")
    }

    "leave out the stub generation without stubgen" in {
      val crate = files(person, RustGeneratorOptions(stubgen = false))
      crate.keySet should not contain "src/bin/stub_gen.rs"
      crate.keySet should not contain "src/stub_utils.rs"
      crate("Cargo.toml") should not include "stubgen"
      crate("src/lib.rs") should not include "gen_stub"
    }

    "put the generated code in a module with handwritten_lib" in {
      val crate = files(
        person + "    tree_root: true\n",
        RustGeneratorOptions(handwrittenLib = true, pyo3 = true),
      )
      crate.keySet should contain allOf (
        "src/lib.rs",
        "src/generated/mod.rs",
        "src/generated/poly.rs",
      )
      crate("src/generated/mod.rs") should include(
        "pub fn register_pymodule(m: &Bound<'_, PyModule>) -> PyResult<()> {",
      )
      val shim = crate("src/lib.rs")
      shim should include(
        "pub mod generated;\n\npub use generated::*;\npub use chrono::NaiveDate;\n",
      )
      shim should include("pub fn load_yaml_person<P>(")
      shim should include("m.add_function(wrap_pyfunction!(load_yaml_person_py, m)?)?;")
    }

    "write the crate as one file" in {
      val code = RustGenerator(using load(person)).serialize()
      code should startWith("// Generated by ohi LinkML from https://example.org/rust/test/\n")
      code should include("#[cfg(feature = \"serde\")]\nmod serde_utils {\n")
      code should include("pub trait InlinedPair: Sized {")
      code should not include "pub mod poly;"
      code should not include "mod stub_utils;"
      code should include("pub struct Person {")
    }

    "name the crate after the schema" in {
      def crateName(schema: String, option: Option[String] = None) =
        RustGenerator(using load(person, schema)).crateName(
          RustGeneratorOptions(crateName = option),
        )
      crateName("my-schema") shouldBe "my_schema"
      crateName("test") shouldBe "test_"
      crateName("fn") shouldBe "fn_"
      crateName("1st") shouldBe RustGenerator.defaultCrateName
      crateName("test", Some("my_crate")) shouldBe "my_crate"
      crateName("serde") shouldBe "serde_"
      for invalid <- Seq("my-crate", "fn", "std", "serde", "_", "1st") do
        withClue(invalid) {
          the[IllegalArgumentException] thrownBy crateName("test", Some(invalid)) should
            have message s"Invalid crate name '$invalid': it must be an ASCII identifier that " +
            "is not a Rust keyword or the name of a Rust library or of a dependency, such as " +
            "'std' or 'serde'."
        }
    }

    "make a struct of each class" in {
      val code = lib(person)
      item(
        code,
